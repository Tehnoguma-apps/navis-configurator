  const sum = (a) => a.reduce((s, x) => s + x, 0);
  q.optional.forEach((c) => { c.subtotal = sum(c[1].map((i) => i[1])); });
  q.equipmentTotal = sum(q.optional.map((c) => c.subtotal));
  q.listTotal = q.boat.basePrice + q.equipmentTotal;
  q.boatDiscount = Math.round(q.boat.basePrice * q.discount.boatPct) / 100;
  q.equipmentDiscount = Math.round(q.equipmentTotal * q.discount.equipmentPct) / 100;
