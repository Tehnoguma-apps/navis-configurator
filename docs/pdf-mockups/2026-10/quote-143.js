window.eur = function (n) {
  const neg = n < 0; n = Math.abs(n);
  const whole = Math.floor(n + 1e-9);
  const cents = Math.round((n - whole) * 100);
  const s = String(whole).replace(/\B(?=(\d{3})+(?!\d))/g, '.');
  return (neg ? '−' : '') + '€' + s + (cents ? ',' + String(cents).padStart(2, '0') : '');
};
